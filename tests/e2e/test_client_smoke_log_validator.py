from __future__ import annotations

import subprocess
import sys
from pathlib import Path

SCRIPT = Path("scripts/validate_client_smoke_log.py")
HEADER = (
    "| client | version | auth path | pat_or_dcr_started_at | registered_at | "
    "first_list_tools_at | elapsed_to_list_tools | list_tools | read_page | "
    "write_agent_page_draft | cross-workspace negative | "
    "restricted-library negative | notes |"
)
SEPARATOR = (
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"
)


def test_client_smoke_log_validator_accepts_completed_log(tmp_path):
    log = tmp_path / "client-smoke.md"
    log.write_text(_valid_log(), encoding="utf-8")

    result = _run_validator(log)

    assert result.returncode == 0, result.stderr
    assert "OK" in result.stdout


def test_client_smoke_log_validator_rejects_placeholders(tmp_path):
    log = tmp_path / "client-smoke.md"
    log.write_text(_valid_log().replace("2.1.74", "<version>", 1), encoding="utf-8")

    result = _run_validator(log)

    assert result.returncode == 1
    assert "placeholder remains" in result.stderr


def test_client_smoke_log_validator_rejects_non_row_placeholders(tmp_path):
    log = tmp_path / "client-smoke.md"
    log.write_text(
        _valid_log()
        + "\n## Command Evidence\n\n"
        + "dtxwiki mcp register-http --url https://<wiki-host>/mcp\n",
        encoding="utf-8",
    )

    result = _run_validator(log)

    assert result.returncode == 1
    assert "placeholder remains" in result.stderr


def test_client_smoke_log_validator_rejects_over_30m(tmp_path):
    log = tmp_path / "client-smoke.md"
    log.write_text(
        _valid_log().replace(
            "2026-05-18T12:09:00+09:00",
            "2026-05-18T12:31:00+09:00",
            1,
        ),
        encoding="utf-8",
    )

    result = _run_validator(log)

    assert result.returncode == 1
    assert "exceeds 30m" in result.stderr


