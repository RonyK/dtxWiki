_REQUEST_LIMIT = 1024 * 1024
_COPY_CHUNK_BYTES = 64 * 1024
_SHA256 = re.compile(r"^[0-9a-f]{64}$")
_REQUEST_KEYS = frozenset(
    {
        "protocol",
        "provider_id",
        "provider_version",
        "distribution_digest",
        "source_path",
        "workspace_id",
        "library_item_id",
        "version_id",
        "input_kind",
        "input_conversion_attempt_id",
        "input_artifact_id",
        "input_sha256",
        "byte_size",
        "format_id",
        "media_type",
        "original_filename",
        "limits",
        "recipe",
        "trace_id",
    }
)
_LIMIT_KEYS = frozenset(field.name for field in fields(PreviewLimits))


class _HostBlobHandle:
    def __init__(self, path: Path, byte_size: int) -> None:
        self.__path = path
        self.byte_size = byte_size

    def open_binary(self) -> BinaryIO:
        return self.__path.open("rb")

    def copy_to(self, destination: Path) -> int:
        copied = 0
        with self.open_binary() as source, destination.open("xb") as output:
            while chunk := source.read(_COPY_CHUNK_BYTES):
                output.write(chunk)
                copied += len(chunk)
        return copied


class _HostPreviewSink(PreviewOutputSink):
    """Keep generated bytes inside scratch and enforce host-side hard caps."""

    def __init__(
        self,
        *,
        scratch: Path,
        limits: PreviewLimits,
        descriptor: PreviewProviderDescriptor,
    ) -> None:
        self._scratch = scratch
        self._limits = limits
        self._descriptor = descriptor
        self._outputs: dict[UUID, tuple[PreviewVariantReceipt, str]] = {}
        self._keys: set[tuple[PreviewVariantKind, int]] = set()
        self._total_bytes = 0

    def write_variant(
        self,
        *,
        source: BinaryIO,
        expected_sha256: str,
        expected_byte_size: int,
        kind: PreviewVariantKind,
        media_type: str,
        renderer_contract: str,
        delivery: PreviewDelivery,
        rank: int,
        ordinal: int = 0,
        filename: str | None = None,
        width: int | None = None,
        height: int | None = None,
        duration_ms: int | None = None,
        page_count: int | None = None,
        metadata: Mapping[str, JsonValue] | None = None,
    ) -> PreviewVariantReceipt:
        if not self._accepts_variant(
            expected_sha256=expected_sha256,
            expected_byte_size=expected_byte_size,
            kind=kind,
            media_type=media_type,
            renderer_contract=renderer_contract,
            delivery=delivery,
            rank=rank,
            ordinal=ordinal,
            width=width,
            height=height,
            duration_ms=duration_ms,
            page_count=page_count,
        ):
            raise PreviewProviderError(
                "preview_output_invalid",
                "The Preview provider output exceeded its approved contract.",
            )

        relative_path = f"variant-{len(self._outputs):03d}.bin"
        output_path = self._scratch / relative_path
        actual_size = 0
        digest = hashlib.sha256()
        try:
            with output_path.open("xb") as output:
                while True:
                    chunk = source.read(_COPY_CHUNK_BYTES)
                    if type(chunk) is not bytes or len(chunk) > _COPY_CHUNK_BYTES:
                        raise PreviewProviderError(
                            "preview_output_invalid",
                            "The Preview provider output stream was invalid.",
                        )
                    if not chunk:
                        break
                    actual_size += len(chunk)
                    if actual_size > expected_byte_size:
                        raise PreviewProviderError(
                            "preview_output_invalid",
                            "The Preview provider output size changed while streaming.",
                        )
                    output.write(chunk)
                    digest.update(chunk)
            if (
                actual_size != expected_byte_size
                or digest.hexdigest() != expected_sha256
            ):
                raise PreviewProviderError(
                    "preview_output_invalid",
                    "The Preview provider output failed integrity validation.",
                )
            output_path.chmod(0o444)
            receipt = PreviewVariantReceipt(
                receipt_id=uuid4(),
                kind=kind,
                media_type=media_type,
                renderer_contract=renderer_contract,
                delivery=delivery,
                byte_size=actual_size,
                sha256=expected_sha256,
                rank=rank,
                ordinal=ordinal,
                filename=filename,
                width=width,
                height=height,
                duration_ms=duration_ms,
                page_count=page_count,
                metadata=metadata or {},
            )
        except Exception:
            output_path.unlink(missing_ok=True)
            raise
        self._outputs[receipt.receipt_id] = (receipt, relative_path)
        self._keys.add((kind, ordinal))
        self._total_bytes += actual_size
        return receipt

    def result_payload(self, result: PreviewResult) -> dict[str, Any]:
        result_ids = tuple(receipt.receipt_id for receipt in result.variants)
        if set(result_ids) != set(self._outputs) or len(result_ids) != len(
            self._outputs
        ):
            raise PreviewProviderError(
                "preview_output_invalid",
                "The Preview provider returned an inconsistent output set.",
            )
        variants: list[dict[str, Any]] = []
        for receipt_id in result_ids:
            receipt, relative_path = self._outputs[receipt_id]
            variants.append(
                {
                    "path": relative_path,
                    "kind": receipt.kind,
                    "media_type": receipt.media_type,
                    "renderer_contract": receipt.renderer_contract,
                    "delivery": receipt.delivery,
                    "byte_size": receipt.byte_size,
                    "sha256": receipt.sha256,
                    "rank": receipt.rank,
                    "ordinal": receipt.ordinal,
                    "filename": receipt.filename,
                    "width": receipt.width,
                    "height": receipt.height,
                    "duration_ms": receipt.duration_ms,
                    "page_count": receipt.page_count,
                    "metadata": thaw_json(receipt.metadata),
                }
            )
        return {
            "protocol": PREVIEW_PROVIDER_SPI_VERSION,
            "provider_id": self._descriptor.provider_id,
            "provider_version": self._descriptor.provider_version,
            "distribution_digest": self._descriptor.distribution_digest,
            "output_schema_version": PREVIEW_OUTPUT_SCHEMA_VERSION,
            "completeness": result.completeness,
            "metadata": thaw_json(result.metadata),
            "variants": variants,
        }

    def _accepts_variant(
        self,
        *,
        expected_sha256: object,
        expected_byte_size: object,
        kind: object,
        media_type: object,
        renderer_contract: object,
        delivery: object,
        rank: object,
        ordinal: object,
        width: object,
        height: object,
        duration_ms: object,
        page_count: object,
    ) -> bool:
        return not (
            type(expected_sha256) is not str
            or not _SHA256.fullmatch(expected_sha256)
            or type(expected_byte_size) is not int
            or expected_byte_size <= 0
            or expected_byte_size > self._limits.max_variant_bytes
            or self._total_bytes + expected_byte_size
            > self._limits.max_total_output_bytes
            or len(self._outputs) >= self._limits.max_variants
            or type(kind) is not str
            or type(media_type) is not str
            or type(renderer_contract) is not str
            or type(delivery) is not str
            or type(rank) is not int
            or rank < 0
            or type(ordinal) is not int
            or ordinal < 0
            or (kind, ordinal) in self._keys
            or renderer_contract not in self._descriptor.output_renderer_contracts
            or media_type not in self._descriptor.output_media_types
            or not renderer_accepts_variant(
                renderer_contract,
                kind=kind,
                media_type=media_type,
                delivery=delivery,
            )
            or (width is None) != (height is None)
            or (width is not None and kind not in {"image", "video"})
            or (page_count is not None and kind != "pdf")
            or (duration_ms is not None and kind not in {"audio", "video"})
            or (width is not None and (type(width) is not int or width <= 0))
            or (height is not None and (type(height) is not int or height <= 0))
            or (
                width is not None
                and height is not None
                and width * height > self._limits.max_pixels
            )
            or (
                page_count is not None
                and (
                    type(page_count) is not int
                    or page_count <= 0
                    or page_count > self._limits.max_pages
                )
            )
            or (
                duration_ms is not None
                and (
                    type(duration_ms) is not int
                    or duration_ms <= 0
                    or duration_ms > self._limits.max_duration_seconds * 1_000
                )
            )
        )


def _plugin(provider_id: str) -> PreviewProviderPlugin:
    if provider_id == "dtxwiki.pillow-image-preview":
        from backend.preview_providers.pillow_image import PillowImagePreviewProvider

        return PillowImagePreviewProvider()
    raise PreviewProviderError(
        "preview_provider_not_allowlisted",
        "The requested Preview provider is not allowlisted by this host.",
        fallback_allowed=False,
    )


def _load_request() -> dict[str, Any]:
    raw = sys.stdin.buffer.read(_REQUEST_LIMIT + 1)
    if len(raw) > _REQUEST_LIMIT:
        raise PreviewProviderError(
            "preview_request_limit",
            "The Preview provider request is too large.",
            fallback_allowed=False,
        )
    try:
        value = json.loads(
            raw,
            parse_constant=lambda _value: (_ for _ in ()).throw(
                ValueError("non-finite JSON number")
            ),
        )
    except (UnicodeError, json.JSONDecodeError, RecursionError, ValueError) as exc:
        raise PreviewProviderError(
            "preview_request_invalid",
            "The Preview provider request is invalid.",
            fallback_allowed=False,
        ) from exc
    if (
        not isinstance(value, dict)
        or set(value) != _REQUEST_KEYS
        or value.get("protocol") != PREVIEW_PROVIDER_SPI_VERSION
    ):
        raise PreviewProviderError(
            "preview_protocol_mismatch",
            "The Preview provider protocol is incompatible.",
            fallback_allowed=False,
        )
    return value


def _preview_request(
    payload: dict[str, Any],
    *,
    descriptor: PreviewProviderDescriptor,
) -> PreviewRequest:
    if (
        payload.get("provider_id") != descriptor.provider_id
        or payload.get("provider_version") != descriptor.provider_version
        or payload.get("distribution_digest") != descriptor.distribution_digest
        or payload.get("source_path") != "source.bin"
    ):
        raise PreviewProviderError(
            "preview_protocol_mismatch",
            "The Preview provider identity is incompatible.",
            fallback_allowed=False,
        )
    source_path = (Path.cwd() / "source.bin").resolve()
    if (
        source_path.parent != Path.cwd().resolve()
        or source_path.is_symlink()
        or not source_path.is_file()
    ):
        raise PreviewProviderError(
            "preview_source_integrity",
            "The Preview source is unavailable.",
            fallback_allowed=False,
        )
    raw_limits = payload.get("limits")
    raw_byte_size = payload.get("byte_size")
    if (
        not isinstance(raw_limits, dict)
        or set(raw_limits) != _LIMIT_KEYS
        or type(raw_byte_size) is not int
        or raw_byte_size <= 0
    ):
        raise PreviewProviderError(
            "preview_request_invalid",
            "The Preview provider limits are invalid.",
            fallback_allowed=False,
        )
    try:
        limits = PreviewLimits(**raw_limits)
    except (TypeError, ValueError) as exc:
        raise PreviewProviderError(
            "preview_request_invalid",
            "The Preview provider limits are invalid.",
            fallback_allowed=False,
        ) from exc
    byte_size = raw_byte_size
    if byte_size > limits.max_input_bytes or source_path.stat().st_size != byte_size:
        raise PreviewProviderError(
            "preview_source_integrity",
            "The Preview source failed integrity validation.",
            fallback_allowed=False,
        )
    digest = _sha256_file(source_path)
    if payload.get("input_sha256") != digest:
        raise PreviewProviderError(
            "preview_source_integrity",
            "The Preview source failed integrity validation.",
            fallback_allowed=False,
        )
    original_filename = payload.get("original_filename")
    if (
        type(original_filename) is not str
        or original_filename in {"", ".", ".."}
        or len(original_filename.encode("utf-8")) > 255
        or any(character in original_filename for character in ("/", "\\", "\x00"))
    ):
        raise PreviewProviderError(
            "preview_request_invalid",
            "The Preview provider filename is invalid.",
            fallback_allowed=False,
        )
    recipe = payload.get("recipe")
    if not isinstance(recipe, dict):
        raise PreviewProviderError(
            "preview_request_invalid",
            "The Preview provider recipe is invalid.",
            fallback_allowed=False,
        )
    try:
        return PreviewRequest(
            workspace_id=UUID(str(payload.get("workspace_id"))),
            library_item_id=UUID(str(payload.get("library_item_id"))),
            version_id=UUID(str(payload.get("version_id"))),
            input_kind=payload.get("input_kind"),
            input_conversion_attempt_id=_optional_uuid(
                payload.get("input_conversion_attempt_id")
            ),
            input_artifact_id=_optional_uuid(payload.get("input_artifact_id")),
            source=_HostBlobHandle(source_path, byte_size),
            input_sha256=digest,
            byte_size=byte_size,
            format_id=payload.get("format_id"),
            media_type=payload.get("media_type"),
            original_filename=original_filename,
            limits=limits,
            recipe=recipe,
            trace_id=payload.get("trace_id"),
        )
    except (TypeError, ValueError) as exc:
        raise PreviewProviderError(
            "preview_request_invalid",
            "The Preview provider request is invalid.",
            fallback_allowed=False,
        ) from exc


def _optional_uuid(value: object) -> UUID | None:
    if value is None:
        return None
    if type(value) is not str:
        raise ValueError("UUID is invalid")
    return UUID(value)


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while chunk := stream.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def _error_payload(error: PreviewProviderError) -> dict[str, Any]:
    return {
        "protocol": PREVIEW_PROVIDER_SPI_VERSION,
        "error": {
            "code": error.code,
            "message": error.safe_message,
            "retryable": error.retryable,
            "fallback_allowed": error.fallback_allowed,
        },
    }


def main(argv: list[str] | None = None) -> int:
    from backend.app.process_tree import guard_managed_parent

    guard_managed_parent()
    parser = argparse.ArgumentParser()
    parser.add_argument("--provider", required=True)
    args = parser.parse_args(argv)
    try:
        plugin = _plugin(args.provider)
        descriptor = plugin.descriptor()
        if descriptor.provider_id != args.provider:
            raise PreviewProviderError(
                "preview_protocol_mismatch",
                "The Preview provider identity is incompatible.",
                fallback_allowed=False,
            )
        health = getattr(plugin, "health", None)
        if callable(health) and health() is not True:
            raise PreviewProviderError(
                "provider_dependency_missing",
                "The bundled Preview provider dependency is unavailable.",
                fallback_allowed=False,
            )
        request = _preview_request(_load_request(), descriptor=descriptor)
        probe = plugin.probe(
            PreviewProbeRequest(
                format_id=request.format_id,
                media_type=request.media_type,
                input_kind=request.input_kind,
                byte_size=request.byte_size,
            )
        )
        if not probe.supported:
            raise UnsupportedPreviewError()
        sink = _HostPreviewSink(
            scratch=Path.cwd(),
            limits=request.limits,
            descriptor=descriptor,
        )
        payload = sink.result_payload(plugin.generate(request, sink))
    except PreviewProviderError as exc:
        payload = _error_payload(exc)
    except Exception:
        payload = _error_payload(
            PreviewProviderError(
                "preview_provider_failed",
                "The Preview provider failed safely.",
                fallback_allowed=True,
            )
        )
    sys.stdout.write(json.dumps(payload, ensure_ascii=False, separators=(",", ":")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
