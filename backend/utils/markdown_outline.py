"""Pure Markdown outline parsing with raw source coordinates."""

from __future__ import annotations

import re
import unicodedata
from bisect import bisect_left
from dataclasses import dataclass
from typing import Literal

from backend.utils.markdown_parser import ParsedMarkdown, parse_markdown

_NON_WORD_RE = re.compile(r"\W+")
SectionKind = Literal["frontmatter", "preamble", "heading"]


@dataclass(frozen=True)
class Section:
    section_id: str
    level: int
    title: str
    heading_path: tuple[str, ...]
    occurrence: int
    line_start: int
    line_end: int
    char_start: int
    char_end: int
    subtree_char_end: int
    body_char_start: int
    kind: SectionKind


@dataclass(frozen=True)
class Outline:
    sections: tuple[Section, ...]


@dataclass(frozen=True)
class _Heading:
    line_index: int
    level: int
    title: str
    heading_path: tuple[str, ...]


def parse_outline(body_md: str) -> Outline:
    """Return the structural sections and exact coordinates of ``body_md``.

    Section identifiers are generated by the server and are intentionally
    opaque to consumers.
    """
    parsed = parse_markdown(body_md)
    lines = parsed.lines
    offsets = parsed.line_offsets
    frontmatter_end_line = parsed.frontmatter_end_line
    headings = _find_headings(parsed)
    subtree_ends = _subtree_ends(headings, offsets, len(body_md))
    first_heading_line = headings[0].line_index if headings else len(lines)
    sections: list[Section] = []
    id_counts: dict[str, int] = {}
    path_counts: dict[tuple[str, ...], int] = {}

    preamble_start_line = 0
    preamble_start_char = 0
    if frontmatter_end_line is not None:
        frontmatter_end_char = parsed.line_end_offset(frontmatter_end_line)
        sections.append(
            Section(
                section_id=_next_section_id("frontmatter", id_counts),
                level=0,
                title="",
                heading_path=(),
                occurrence=_next_occurrence((), path_counts),
                line_start=1,
                line_end=frontmatter_end_line + 1,
                char_start=0,
                char_end=frontmatter_end_char,
                subtree_char_end=frontmatter_end_char,
                body_char_start=0,
                kind="frontmatter",
            )
        )
        preamble_start_line = frontmatter_end_line + 1
        preamble_start_char = frontmatter_end_char

    preamble_end_char = (
        offsets[first_heading_line] if headings else len(body_md)
    )
    if preamble_start_char < preamble_end_char:
        sections.append(
            Section(
                section_id=_next_section_id("preamble", id_counts),
                level=0,
                title="",
                heading_path=(),
                occurrence=_next_occurrence((), path_counts),
                line_start=preamble_start_line + 1,
                line_end=_inclusive_line_end(parsed, preamble_end_char),
                char_start=preamble_start_char,
                char_end=preamble_end_char,
                subtree_char_end=preamble_end_char,
                body_char_start=preamble_start_char,
                kind="preamble",
            )
        )

    for index, heading in enumerate(headings):
        next_heading_line = (
            headings[index + 1].line_index
            if index + 1 < len(headings)
            else None
        )
        char_end = (
            offsets[next_heading_line]
            if next_heading_line is not None
            else len(body_md)
        )
        sections.append(
            Section(
                section_id=_next_section_id(heading.title, id_counts),
                level=heading.level,
                title=heading.title,
                heading_path=heading.heading_path,
                occurrence=_next_occurrence(heading.heading_path, path_counts),
                line_start=heading.line_index + 1,
                line_end=_inclusive_line_end(parsed, char_end),
                char_start=offsets[heading.line_index],
                char_end=char_end,
                subtree_char_end=subtree_ends[index],
                body_char_start=parsed.line_end_offset(heading.line_index),
                kind="heading",
            )
        )

    return Outline(sections=tuple(sections))


def _find_headings(parsed: ParsedMarkdown) -> list[_Heading]:
    """Collect document-level headings from a single CommonMark parse.

    markdown-it is the sole structural authority: a
    `heading_open` token is a real ATX or Setext heading exactly when
    CommonMark says so, `token.level == 0` excludes one nested inside a
    list/blockquote, and a fenced code block or raw HTML block never emits
    `heading_open` for a "#" line inside it -- CommonMark's own block rules
    (marker-length-aware fence closers, indentation limits, blank-line
    requirements) resolve these for free instead of being re-derived by a
    parallel regex/state-machine that can silently disagree with them.

    A heading's rendered title comes from its immediate `inline` child's raw
    (still-unrendered) content -- markdown-it strips the optional ATX closing
    sequence exactly per spec (a trailing "#"-run counts as a closer only
    when whitespace-preceded, so "## C#" keeps its content hash), matching
    what any CommonMark-conformant renderer shows.
    """
    tokens = parsed.tokens

    raw_headings: list[tuple[int, int, str]] = []
    for index, token in enumerate(tokens):
        if token.type != "heading_open" or token.level != 0 or token.map is None:
            continue
        line_index = token.map[0]
        title = ""
        following = tokens[index + 1] if index + 1 < len(tokens) else None
        if following is not None and following.type == "inline":
            title = following.content
        raw_headings.append((line_index, int(token.tag[1:]), title))

    headings: list[_Heading] = []
    stack: list[tuple[int, str]] = []
    for line_index, level, title in raw_headings:
        while stack and stack[-1][0] >= level:
            stack.pop()
        heading_path = tuple([item[1] for item in stack] + [title])
        headings.append(
            _Heading(
                line_index=line_index,
                level=level,
                title=title,
                heading_path=heading_path,
            )
        )
        stack.append((level, title))
    return headings


def _subtree_ends(
    headings: list[_Heading], offsets: tuple[int, ...], body_length: int
) -> list[int]:
    ends = [body_length] * len(headings)
    open_headings: list[int] = []
    for index, heading in enumerate(headings):
        while (
            open_headings
            and headings[open_headings[-1]].level >= heading.level
        ):
            ends[open_headings.pop()] = offsets[heading.line_index]
        open_headings.append(index)
    return ends


def _inclusive_line_end(parsed: ParsedMarkdown, char_end: int) -> int:
    """Return the 1-based inclusive line containing ``char_end``'s span."""

    return max(bisect_left(parsed.line_offsets, char_end), 1)


def _next_section_id(title: str, counts: dict[str, int]) -> str:
    normalized = unicodedata.normalize("NFC", title).lower()
    base = _NON_WORD_RE.sub("-", normalized).strip("-") or "section"
    occurrence = counts.get(base, 0) + 1
    counts[base] = occurrence
    return base if occurrence == 1 else f"{base}-{occurrence}"


def _next_occurrence(
    heading_path: tuple[str, ...], counts: dict[tuple[str, ...], int]
) -> int:
    occurrence = counts.get(heading_path, 0) + 1
    counts[heading_path] = occurrence
    return occurrence
