import { i18n } from "../i18n";

/**
 * Fixed-copy review reasons (I18N-08a). The server stores the English prose
 * and, for fixed copy, a stable code; Review and Activity translate the code
 * with one table. Caller-written reasons have no code and stay as written.
 * To add a reason: give the server copy a code, add it here with its English
 * default, and add `review:decisionSummary.<code>` to every locale.
 */
export const DECISION_SUMMARY_DEFAULTS = {
  context_draft_requires_review: "Context draft requires review",
  context_update_requires_review: "Context update draft requires review",
  context_update_workflow_sequence_incomplete:
    "Context update draft requires review because the workflow sequence is incomplete",
  context_ingress_requires_review: "Ask capture requires review",
  context_draft_restored_after_rejection: "Draft restored after a later draft was rejected",
  agent_page_write_requires_review: "AI-written page change requires human review",
  page_write_held_for_review: "Page change held for review",
  agent_page_write_approved_by_policy: "AI-written page change approved by policy",
  human_page_write_applied: "Human page change applied directly",
  stale_edit_preserved_as_alternative: "Stale edit kept as an alternative draft",
  client_llm_draft_requires_review: "Draft generated by a client AI requires human review",
} as const;
export type DecisionSummaryCode = keyof typeof DECISION_SUMMARY_DEFAULTS;

// Rows stored before their fixed copy had a code. Exact matches only: free
// text that merely resembles a fixed reason is shown as written.
const LEGACY_FIXED_SUMMARIES: Readonly<Record<string, DecisionSummaryCode>> = {
  "agent-authored page write requires human review": "agent_page_write_requires_review",
  "page write held for review": "page_write_held_for_review",
  "agent-authored page write approved by policy": "agent_page_write_approved_by_policy",
  "human page write applied directly": "human_page_write_applied",
  "stale edit preserved as alternative draft": "stale_edit_preserved_as_alternative",
  "Generated by borrowed intelligence; human review required.": "client_llm_draft_requires_review",
};
// Ask capture reviews used to store their raw reason codes as the summary prose.
const LEGACY_INGRESS_REASON_SUMMARY = /^(low_confidence|page_type_decision)(,(low_confidence|page_type_decision))*$/;

export type DecisionSummaryCarrier = {
  decision_summary?: string | null;
  decision_summary_code?: string | null;
  review_type?: string | null;
};

/** The stable code for a reason, if it is fixed copy (stored or legacy). */
export function decisionSummaryCode(item: DecisionSummaryCarrier): DecisionSummaryCode | null {
  const summary = item.decision_summary ?? "";
  const code = item.decision_summary_code
    ?? (item.review_type === "context_ingress_accept" && LEGACY_INGRESS_REASON_SUMMARY.test(summary)
      ? "context_ingress_requires_review"
      : Object.hasOwn(LEGACY_FIXED_SUMMARIES, summary) ? LEGACY_FIXED_SUMMARIES[summary] : null);
  return code && Object.hasOwn(DECISION_SUMMARY_DEFAULTS, code) ? code as DecisionSummaryCode : null;
}

export function localizedDecisionSummary(item: DecisionSummaryCarrier): string | null {
  const code = decisionSummaryCode(item);
  if (code) {
    return i18n.t(`review:decisionSummary.${code}`, { defaultValue: DECISION_SUMMARY_DEFAULTS[code] });
  }
  // Legacy rows, caller-authored free text, and future server codes unknown to
  // this client keep the stored prose instead of exposing an i18n key.
  return item.decision_summary ?? null;
}
